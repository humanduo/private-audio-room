function updateMetadataAnalyzeJob(jobId: string, patch: Partial<MetadataAnalyzeJob>) {
  const current = metadataAnalyzeJobs.get(jobId);
  if (!current) return null;
  const next = { ...current, ...patch };
  metadataAnalyzeJobs.set(jobId, next);
  return next;
}

async function runMetadataAnalyzeJob(jobId: string) {
  const job = metadataAnalyzeJobs.get(jobId);
  if (!job) return;

  if (!process.env.DEEPSEEK_API_KEY) {
    updateMetadataAnalyzeJob(jobId, {
      status: 'failed',
      error: 'DEEPSEEK_API_KEY is not configured',
      finishedAt: nowIso()
    });
    return;
  }

  updateMetadataAnalyzeJob(jobId, { status: 'running' });
  const state = readState();
  const candidates = selectMetadataAnalyzeCandidates(state, job.kind, job.mode, job.limit);
  updateMetadataAnalyzeJob(jobId, { total: candidates.length });

  for (const { album, index } of candidates) {
    updateMetadataAnalyzeJob(jobId, { currentAlbumTitle: album.title });
    try {
      if (shouldSkipMetadataAnalyze(state.albums[index])) {
        const current = metadataAnalyzeJobs.get(jobId);
        if (!current) return;
        updateMetadataAnalyzeJob(jobId, {
          processed: current.processed + 1,
          skipped: current.skipped + 1,
          results: [
            ...current.results,
            {
              id: album.id,
              title: album.title,
              ok: true,
              skipped: true,
              aiMetaStatus: state.albums[index].aiMetaStatus
            }
          ]
        });
        continue;
      }
      const metadata = await analyzeAlbumMetadataWithDeepSeek(album);
      const autoApply = canAutoApplyMetadata(metadata);
      if (autoApply) {
        state.albums[index] = applyAiMetadataToAlbum(state.albums[index], { ...metadata, needsReview: false }, state.albums);
      } else {
        upsertPendingMetadata(state, state.albums[index], metadata, '搜索来源不足或置信度较低，需要确认后写入。');
        state.albums[index] = {
          ...state.albums[index],
          aiMetaStatus: 'suggested',
          aiMetaUpdatedAt: new Date().toISOString()
        };
      }
      writeState(state);
      const current = metadataAnalyzeJobs.get(jobId);
      if (!current) return;
      updateMetadataAnalyzeJob(jobId, {
        processed: current.processed + 1,
        updated: current.updated + 1,
        results: [
          ...current.results,
          {
            id: album.id,
            title: album.title,
            ok: true,
            needsReview: !autoApply,
            aiMetaStatus: state.albums[index].aiMetaStatus
          }
        ]
      });
    } catch (error) {
      state.albums[index] = {
        ...state.albums[index],
        aiMetaStatus: 'failed',
        aiMetaUpdatedAt: new Date().toISOString()
      };
      writeState(state);
      const current = metadataAnalyzeJobs.get(jobId);
      if (!current) return;
      updateMetadataAnalyzeJob(jobId, {
        processed: current.processed + 1,
        failed: current.failed + 1,
        results: [
          ...current.results,
          {
            id: album.id,
            title: album.title,
            ok: false,
            error: error instanceof Error ? error.message : 'DeepSeek metadata analysis failed'
          }
        ]
      });
    }
  }

  updateMetadataAnalyzeJob(jobId, {
    status: 'completed',
    currentAlbumTitle: '',
    finishedAt: nowIso()
  });
}

function mergeManualMetadata(scanned: Album[], existing: Album[]) {
  const existingById = new Map(existing.map((album) => [album.id, album]));
  const existingByTitle = new Map(existing.map((album) => [album.title, album]));

  function mergeEpisodesWithPlayback(nextEpisodes: Episode[], previousEpisodes: Episode[]) {
    const previousById = new Map(previousEpisodes.map((episode) => [episode.id, episode]));
    const previousByPath = new Map(previousEpisodes.filter((episode) => episode.filePath).map((episode) => [episode.filePath, episode]));
    const previousByRelativePath = new Map(previousEpisodes.filter((episode) => episode.relativePath).map((episode) => [episode.relativePath, episode]));
    const previousByTitle = new Map(previousEpisodes.map((episode) => [episode.title, episode]));

    return nextEpisodes.map((episode) => {
      const previous =
        previousByRelativePath.get(episode.relativePath || '') ||
        previousById.get(episode.id) ||
        previousByPath.get(episode.filePath || '') ||
        previousByTitle.get(episode.title);
      if (!previous) return episode;
      return {
        ...episode,
        relativePath: episode.relativePath || previous.relativePath,
        progress: finiteNumber(previous.progress, episode.progress || 0),
        currentTime: finiteNumber(previous.currentTime, episode.currentTime || 0),
        durationSeconds: finiteNumber(previous.durationSeconds, episode.durationSeconds || 0),
        lastPlayedAt: previous.lastPlayedAt || episode.lastPlayedAt,
        duration: previous.duration && previous.duration !== '--:--' ? previous.duration : episode.duration
      };
    });
  }

  return scanned.map((album) => {
    const previous = existingById.get(album.id) || existingByTitle.get(album.title);
    if (!previous) return album;
    const hasCustomCover =
      previous.cover?.startsWith('data:image/') || previous.cover?.startsWith('/covers/') || previous.cover?.startsWith('/assets/');
    return {
      ...album,
      cover: hasCustomCover ? previous.cover : album.cover,
      status: previous.status || album.status,
      progress: finiteNumber(previous.progress, album.progress),
      currentEpisodeId: previous.currentEpisodeId || album.currentEpisodeId,
      currentTime: finiteNumber(previous.currentTime, album.currentTime || 0),
      durationSeconds: finiteNumber(previous.durationSeconds, album.durationSeconds || 0),
      lastPlayedAt: previous.lastPlayedAt || album.lastPlayedAt,
      tags: cleanMetadataTags([...(album.tags || []), ...(previous.tags || []), ...(previous.genres || [])]),
      description: previous.description && previous.description !== `来自 NAS 目录：${album.title}` ? previous.description : album.description,
      author: previous.author || album.author,
      cast: uniqueStrings(previous.cast || album.cast || []),
      platform: previous.platform || album.platform,
      summary: previous.summary || album.summary,
      genres: cleanMetadataTags(previous.genres || album.genres || []),
      relationship: previous.relationship || album.relationship,
      audience: previous.audience || album.audience,
      finishStatus: previous.finishStatus || album.finishStatus,
      metadataSources: previous.metadataSources || album.metadataSources,
      aiMetaStatus: previous.aiMetaStatus || album.aiMetaStatus,
      aiMetaUpdatedAt: previous.aiMetaUpdatedAt || album.aiMetaUpdatedAt,
      episodes: mergeEpisodesWithPlayback(album.episodes, previous.episodes || [])
    };
  });
}

function isPathInsideRoot(filePath: string, root: string) {
  const relative = path.relative(path.resolve(root), path.resolve(filePath));
  return relative === '' || (!relative.startsWith('..') && !path.isAbsolute(relative));
}

function safeStat(filePath: string) {
  try {
    return fs.statSync(filePath);
  } catch {
    return null;
  }
}

function findFolderCover(folderPath: string) {
  for (const fileName of coverFileNames) {
    const coverPath = path.join(folderPath, fileName);
    const stat = safeStat(coverPath);
    if (!stat?.isFile()) continue;

    const ext = path.extname(fileName).toLowerCase();
    const mime = ext === '.png' ? 'image/png' : 'image/jpeg';
    const data = fs.readFileSync(coverPath);
    return `data:${mime};base64,${data.toString('base64')}`;
  }

  return '';
}

function audioContentType(filePath: string) {
  const lower = filePath.toLowerCase();
  const ext = path.extname(lower);
  if (ext === '.mp3') return 'audio/mpeg';
  if (ext === '.m4a' || ext === '.m4b' || ext === '.aac') return 'audio/mp4';
  if (ext === '.flac') return 'audio/flac';
  if (ext === '.wav') return 'audio/wav';
  if (ext === '.ogg' || ext === '.opus') return 'audio/ogg';
  if (lower.endsWith('mp3')) return 'audio/mpeg';
  if (lower.endsWith('m4a') || lower.endsWith('m4b') || lower.endsWith('aac')) return 'audio/mp4';
  if (lower.endsWith('flac')) return 'audio/flac';
  if (lower.endsWith('wav')) return 'audio/wav';
  if (lower.endsWith('ogg') || lower.endsWith('opus')) return 'audio/ogg';
  return 'application/octet-stream';
}

