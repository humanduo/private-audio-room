function normalizeMetadataSearchTitle(title: string) {
  return seriesTitleForMetadata(title)
    .replace(/[\s·・_-]*第[一二三四五六七八九十两\d]+季(?:[（(][上下][）)])?/gu, '')
    .replace(/[\s·・_-]*(上季|下季|完结|广播剧|有声书)/gu, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function normalizeTitleForMatch(value: string) {
  return normalizeMetadataSearchTitle(value)
    .replace(/[《》"'“”‘’（）()[\]【】\s·・._-]/g, '')
    .toLowerCase();
}

function isTitleMatched(album: Album, metadata: AiMetadata) {
  const expected = normalizeTitleForMatch(album.title);
  const actual = normalizeTitleForMatch(metadata.title);
  if (!expected || !actual) return false;
  if (actual.length < 4 && expected !== actual) return false;
  return actual.includes(expected) || expected.includes(actual);
}

function sourceText(result: SearchResult) {
  return `${result.title} ${result.summary || ''} ${result.snippet || ''} ${result.url}`.toLowerCase();
}

function isLowQualitySource(result: SearchResult) {
  const text = sourceText(result);
  return /盗文|笔趣阁|小说网|漫画|无弹窗|全文阅读|txt下载|聚合|采集|章节目录/i.test(text);
}

function isHighQualitySource(result: SearchResult) {
  const text = sourceText(result);
  return (
    /missevan|猫耳|manbo|漫播|fanqie|饭角|music\.163|网易云音乐|ximalaya|喜马拉雅|douban|豆瓣|官方微博|官博|官方发布|完整制作组|制作组|配音组/i.test(text) &&
    !isLowQualitySource(result)
  );
}

function isDramaRelatedSource(result: SearchResult) {
  const text = sourceText(result);
  return /广播剧|有声剧|猫耳|漫播|饭角|网易云音乐|喜马拉雅|主役|cv|配音|制作组|剧组|原著/i.test(text) && !isLowQualitySource(result);
}

function extractAuthorFromSearchResults(results: SearchResult[]) {
  for (const result of results) {
    const text = `${result.title} ${result.summary || ''} ${result.snippet || ''}`;
    const match = text.match(/(?:原著作者|原著|原作|作者)\s*[:：]\s*([^\s，,。；;、｜|《》【】()[\]（）]{2,20})/);
    if (match?.[1] && !/广播剧|猫耳|漫播|饭角|网易云音乐|喜马拉雅|制作组|工作室/.test(match[1])) return match[1].trim();
  }
  return '';
}

function extractPlatformFromSearchResults(results: SearchResult[]) {
  const text = results.map(sourceText).join(' ');
  if (/missevan|猫耳/.test(text)) return '猫耳 FM';
  if (/manbo|漫播/.test(text)) return '漫播';
  if (/fanqie|饭角/.test(text)) return '饭角';
  if (/music\.163|网易云音乐/.test(text)) return '网易云音乐';
  if (/ximalaya|喜马拉雅/.test(text)) return '喜马拉雅';
  return '';
}

async function searchMetadataQuery(query: string) {
  const headers = {
    'User-Agent': 'Mozilla/5.0 PrivateAudioRoom/0.1',
    Accept: 'text/html,application/xhtml+xml'
  };
  let duckStatus = 'error';

  try {
    const duckResponse = await fetch(`https://duckduckgo.com/html/?q=${encodeURIComponent(query)}`, { headers, signal: AbortSignal.timeout(9000) });
    duckStatus = String(duckResponse.status);
    if (duckResponse.ok) {
      const html = await duckResponse.text();
      const duckResults = [...html.matchAll(/<a rel="nofollow" class="result__a" href="([^"]+)">([\s\S]*?)<\/a>[\s\S]*?<a class="result__snippet"[\s\S]*?>([\s\S]*?)<\/a>/g)]
        .slice(0, 5)
        .map((match) => ({
          title: cleanHtmlText(match[2]).slice(0, 120),
          snippet: cleanHtmlText(match[3]).slice(0, 520),
          url: decodeDuckDuckGoUrl(match[1]).slice(0, 300),
          source: 'duckduckgo'
        }))
        .filter((item) => item.title || item.snippet);
      if (duckResults.length) return duckResults;
    }
  } catch (error) {
    duckStatus = error instanceof Error ? error.message : 'error';
  }

  const bingResponse = await fetch(`https://www.bing.com/search?q=${encodeURIComponent(query)}`, { headers, signal: AbortSignal.timeout(9000) });
  if (!bingResponse.ok) throw new Error(`metadata search failed: duck=${duckStatus} bing=${bingResponse.status}`);

  const html = await bingResponse.text();
  return [...html.matchAll(/<li class="b_algo"[\s\S]*?<h2[^>]*>\s*<a[^>]+href="([^"]+)"[^>]*>([\s\S]*?)<\/a>[\s\S]*?(?:<p[^>]*>([\s\S]*?)<\/p>)?/g)]
    .slice(0, 5)
    .map((match) => ({
      title: cleanHtmlText(match[2]).slice(0, 120),
      snippet: cleanHtmlText(match[3]).slice(0, 520),
      url: decodeBingUrl(match[1]).slice(0, 300),
      source: 'bing'
    }))
    .filter((item) => item.title || item.snippet);
}

async function bochaSearch(query: string, options: { maxResults?: number; timeoutMs?: number } = {}): Promise<SearchResult[]> {
  const apiKey = process.env.BOCHA_API_KEY;
  if (!apiKey) throw new Error('未配置 BOCHA_API_KEY，无法联网搜索。');
  const response = await fetch('https://api.bochaai.com/v1/web-search', {
    method: 'POST',
    signal: AbortSignal.timeout(options.timeoutMs || searchTimeoutMs()),
    headers: {
      Authorization: `Bearer ${apiKey}`,
      'Content-Type': 'application/json'
    },
    body: JSON.stringify({
      query,
      freshness: 'noLimit',
      summary: true,
      count: options.maxResults || searchMaxResults()
    })
  });
  const data = await response.json().catch(() => ({}));
  if (!response.ok) {
    const message = data?.error?.message || data?.message || `Bocha search failed: ${response.status}`;
    throw new Error(message);
  }

  const rawResults =
    data?.data?.webPages?.value ||
    data?.data?.webPages ||
    data?.webPages?.value ||
    data?.results ||
    data?.data?.results ||
    [];
  if (!Array.isArray(rawResults)) throw new Error('Bocha 返回格式缺少搜索结果列表。');
  const results = rawResults
    .map((item: Record<string, unknown>) => ({
      title: stringField(item.name || item.title, 120),
      url: stringField(item.url || item.link, 400),
      snippet: stringField(item.snippet || item.description || item.content, 700),
      summary: stringField(item.summary, 1000),
      source: 'bocha'
    }))
    .filter((item) => item.title && item.url)
    .slice(0, options.maxResults || searchMaxResults());
  if (!results.length) throw new Error(`Bocha 没有返回可用搜索结果：${query}`);
  return results;
}

async function searchWithProvider(query: string, options: { maxResults?: number; timeoutMs?: number; provider?: string } = {}): Promise<SearchResult[]> {
  const provider = (options.provider || searchProviderName()).toLowerCase();
  let results: SearchResult[] = [];
  if (provider === 'bocha') results = await bochaSearch(query, options);
  else if (provider === 'duckduckgo' || provider === 'bing') results = await searchMetadataQuery(query);
  else if (provider === 'baidu') throw new Error('BAIDU_APPBUILDER_API_KEY provider is not implemented yet');
  else if (provider === 'tavily') throw new Error('TAVILY_API_KEY provider is not implemented yet');
  else if (provider === 'brave') throw new Error('BRAVE_API_KEY provider is not implemented yet');
  else throw new Error(`未知搜索 provider：${provider}`);

  if (!results.length) throw new Error(`搜索没有返回可用结果：${query}`);
  return results.slice(0, options.maxResults || searchMaxResults());
}

function albumSearchQueries(album: Album) {
  const baseTitle = normalizeMetadataSearchTitle(album.title) || album.title;
  return uniqueStrings([
    `${baseTitle} 广播剧`,
    `${baseTitle} 原著 配音`,
    `${baseTitle} 猫耳`,
    `${baseTitle} 漫播`,
    `${baseTitle} 网易云音乐`
  ]).slice(0, 2);
}

async function searchAlbumMetadata(album: Album) {
  if (process.env.AI_METADATA_ALLOW_WEB_SEARCH === 'false') throw new Error('AI_METADATA_ALLOW_WEB_SEARCH=false，已关闭联网搜索，不能自动整理资料。');

  const queries = albumSearchQueries(album);
  const results: SearchResult[] = [];
  for (const query of queries) {
    results.push(...(await searchWithProvider(query)));
    if (results.some(isHighQualitySource) || results.length >= searchMaxResults()) break;
  }
  const seen = new Set<string>();
  return results
    .filter((item) => {
      const key = `${item.title}-${item.url}`;
      if (seen.has(key)) return false;
      seen.add(key);
      return !isLowQualitySource(item);
    })
    .sort((a, b) => Number(isHighQualitySource(b)) - Number(isHighQualitySource(a)))
    .slice(0, searchMaxResults());
}

