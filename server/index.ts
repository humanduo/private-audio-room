app.use((req, res, next) => {
  const startedAt = Date.now();
  let responseBytes = 0;
  const originalWrite = res.write.bind(res);
  const originalEnd = res.end.bind(res);

  res.write = ((chunk: unknown, ...args: unknown[]) => {
    if (chunk) responseBytes += Buffer.isBuffer(chunk) ? chunk.length : Buffer.byteLength(String(chunk));
    return originalWrite(chunk as never, ...(args as never[]));
  }) as typeof res.write;

  res.end = ((chunk: unknown, ...args: unknown[]) => {
    if (chunk) responseBytes += Buffer.isBuffer(chunk) ? chunk.length : Buffer.byteLength(String(chunk));
    return originalEnd(chunk as never, ...(args as never[]));
  }) as typeof res.end;

  res.on('finish', () => {
    const elapsedMs = Date.now() - startedAt;
    const contentLength = Number(res.getHeader('content-length') || 0);
    const size = contentLength || responseBytes;
    if (req.path === '/api/home') {
      apiMetrics.lastHomeApiMs = elapsedMs;
      apiMetrics.homeResponseSize = size;
    }
    if (req.path === '/api/albums') apiMetrics.lastAlbumsApiMs = elapsedMs;
    if (req.path.startsWith('/api/')) {
      console.log(`[api] ${req.method} ${req.originalUrl} ${elapsedMs}ms size=${Math.round(size / 1024)}kb`);
    }
  });
  next();
});

